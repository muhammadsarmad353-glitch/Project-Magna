"""Gemma 4 "voice mode" (text input) - rider request -> ride settings.

Maps what the rider says ("I feel carsick", "I'm late!", "show me what it can do") to a
controller config for the team controller: mode (sport|comfort) plus bounded speed_scale and
margin_extra, and a short spoken-style reply. Gemma only picks among safe, pre-tested settings.

    python gemma/voice_mode.py "I feel carsick"            # one request -> gemma/rider_config.yaml
    python gemma/voice_mode.py                             # interactive prompt
Then run e.g.
    python -m autocross run -c controllers/ua_team/pure_pursuit_racing.py -t tracks/practice_technical.yaml \
        --backend bicycle --controller-config gemma/rider_config.yaml
or with the live strategist:  python gemma/run_demo.py --controller-config gemma/rider_config.yaml --rider "..."
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from llm import LLMUnavailable, get_backend, parse_json  # noqa: E402

OUT = Path(__file__).resolve().parent / "rider_config.yaml"

SYS_RIDER = """You are the voice assistant of a self-driving EcoCAR. Map the rider's request to ride settings.
Reply with ONE JSON object: {"mode": "sport" or "comfort", "speed_scale": number 0.6-1.0, \
"margin_extra": number 0.0-0.3, "reply": "one friendly sentence to say to the rider"}.
comfort = gentle (low g, smooth braking) for carsick, nervous, sleepy, eating/drinking, children, "slow down".
sport = fastest safe lap for "I'm late", "hurry", "show me what it can do".
speed_scale below 1.0 and margin_extra above 0 make it even gentler and safer. Never exceed these bounds."""

COMFORT_WORDS = ("sick", "nause", "slow", "gentle", "scared", "nervous", "careful", "smooth", "coffee", "baby",
                 "kid", "sleep", "dizzy", "calm", "relax", "easy")
SPORT_WORDS = ("late", "hurry", "fast", "quick", "rush", "sport", "race", "go go", "what it can do")


def rules(text: str) -> dict:
    t = text.lower()
    if any(w in t for w in COMFORT_WORDS):
        strong = any(w in t for w in ("sick", "nause", "dizzy", "scared", "baby"))
        return {"mode": "comfort", "speed_scale": 0.8 if strong else 0.9, "margin_extra": 0.1 if strong else 0.0,
                "reply": "Got it - switching to comfort mode for a smoother ride."}
    if any(w in t for w in SPORT_WORDS):
        return {"mode": "sport", "speed_scale": 1.0, "margin_extra": 0.0,
                "reply": "Hold on - sport mode, fastest safe line."}
    return {"mode": "sport", "speed_scale": 1.0, "margin_extra": 0.0, "reply": "Keeping the standard settings."}


def clamp(d: dict) -> dict:
    mode = str(d.get("mode", "sport")).lower()
    return {"mode": mode if mode in ("sport", "comfort") else "sport",
            "speed_scale": round(min(1.0, max(0.6, float(d.get("speed_scale", 1.0)))), 2),
            "margin_extra": round(min(0.3, max(0.0, float(d.get("margin_extra", 0.0)))), 2),
            "reply": str(d.get("reply", ""))[:200]}


def interpret(text: str, backend_name: str | None = None) -> tuple[dict, str]:
    try:
        be = get_backend(backend_name)
        d = clamp(parse_json(be.chat(SYS_RIDER, "Rider said: " + text, json_mode=True, max_tokens=150, timeout=60)))
        return d, getattr(be, "last_used", None) or be.name
    except (LLMUnavailable, ValueError, TypeError) as e:
        return clamp(rules(text)), f"keyword rules (model unavailable: {e})"


def to_yaml(d: dict, text: str) -> str:
    """Config for the team controller (mode/margin/mu_frac...) - speed_scale/margin_extra are baked in
    so the plain scored controller can use it; the Gemma wrapper reads the same keys."""
    base_margin, mu, dec, acc = 0.55, 0.83, 0.75, 1.0
    lines = [f"# generated by gemma/voice_mode.py from rider request: {json.dumps(text)}",
             f"mode: {d['mode']}"]
    if d["mode"] == "comfort":
        lines += ["comfort_lat_g: 0.35", "comfort_lon_g: 0.30", "comfort_jerk: 2.5"]
    if d["margin_extra"] > 0:
        lines.append(f"margin: {base_margin + d['margin_extra']:.2f}")
    if d["speed_scale"] < 1.0:
        lines += [f"mu_frac: {mu * d['speed_scale']:.3f}", f"dec_frac: {dec * d['speed_scale']:.3f}",
                  f"acc_frac: {acc * d['speed_scale']:.3f}"]
    return "\n".join(lines) + "\n"


def handle(text: str, backend: str | None, write: bool) -> dict:
    d, used = interpret(text, backend)
    print(f'Rider: "{text}"\n  [{used}] -> mode={d["mode"]} speed_scale={d["speed_scale"]} '
          f'margin_extra={d["margin_extra"]}\n  Car: {d["reply"]}')
    if write:
        OUT.write_text(to_yaml(d, text))
        print(f"  wrote {OUT}")
    return d


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("text", nargs="*")
    ap.add_argument("--backend")
    ap.add_argument("--no-write", action="store_true", help="don't write gemma/rider_config.yaml")
    a = ap.parse_args()
    if a.text:
        handle(" ".join(a.text), a.backend, not a.no_write)
        return
    print("Type a request (empty line to quit).")
    while True:
        try:
            t = input("> ").strip()
        except EOFError:
            break
        if not t:
            break
        handle(t, a.backend, not a.no_write)


if __name__ == "__main__":
    main()
